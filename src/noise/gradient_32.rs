use crate::noise::hash3d_32::hash3d_i32;

use simdeez::prelude::*;

/// Mixes the seed into a position hash so that *every* bit of the seed affects
/// the gradient selection.
///
/// The low-dimensional gradient pickers (`grad1`/`grad2`/`grad4`) mask the hash
/// down to 3-5 bits. Previously the seed was only XOR'd in before masking, so
/// only the low bits of the seed survived and `with_seed` had a period of 8
/// (issue #42). Running the combined value through the same avalanche mixer that
/// `hash3d` uses spreads the high seed bits down into the masked bits.
#[inline(always)]
fn seed_hash<S: Simd>(seed: i32, hash: S::Vi32) -> S::Vi32 {
    let mut h = S::Vi32::set1(seed) ^ hash;
    h = ((h * h) * S::Vi32::set1(60493)) * h;
    (h >> 13) ^ h
}

/// Generates a random integer gradient in ±7 inclusive
///
/// This differs from Gustavson's well-known implementation in that gradients can be zero, and the
/// maximum gradient is 7 rather than 8.
#[inline(always)]
pub fn grad1<S: Simd>(seed: i32, hash: S::Vi32) -> S::Vf32 {
    let h = seed_hash::<S>(seed, hash) & S::Vi32::set1(15);
    let v = (h & S::Vi32::set1(7)).cast_f32();

    let h_and_8 = ((h & S::Vi32::set1(8)).cmp_eq(S::Vi32::zeroes())).bitcast_f32();
    h_and_8.blendv(S::Vf32::zeroes() - v, v)
}

/// Generates a random gradient vector where one component is ±1 and the other is ±2.
///
/// This differs from Gustavson's gradients by having a constant magnitude, providing results that
/// are more consistent between directions.
#[inline(always)]
pub fn grad2<S: Simd>(seed: i32, hash: S::Vi32) -> [S::Vf32; 2] {
    let h = seed_hash::<S>(seed, hash) & S::Vi32::set1(7);
    let mask = (S::Vi32::set1(4).cmp_gt(h)).bitcast_f32();
    let x_magnitude = mask.blendv(S::Vf32::set1(2.0), S::Vf32::set1(1.0));
    let y_magnitude = mask.blendv(S::Vf32::set1(1.0), S::Vf32::set1(2.0));

    let h_and_1 = ((h & S::Vi32::set1(1)).cmp_eq(S::Vi32::zeroes())).bitcast_f32();
    let h_and_2 = ((h & S::Vi32::set1(2)).cmp_eq(S::Vi32::zeroes())).bitcast_f32();

    let gx = mask
        .blendv(h_and_2, h_and_1)
        .blendv(S::Vf32::zeroes() - x_magnitude, x_magnitude);
    let gy = mask
        .blendv(h_and_1, h_and_2)
        .blendv(S::Vf32::zeroes() - y_magnitude, y_magnitude);
    [gx, gy]
}

/// Selects one of the 12 balanced Gustavson edge gradients uniformly from the
/// position hash and returns its `[gx, gy, gz]`.
///
/// The 12 gradients are the vectors with one zero component and two `±1`
/// components. They fall into three blocks of four by which axis is zero:
///   index 0-3   -> (±1, ±1,  0)
///   index 4-7   -> (±1,  0, ±1)
///   index 8-11  -> ( 0, ±1, ±1)
/// Within a block, bit 0 of the index picks the first sign and bit 1 the
/// second. Selecting the index as `hash mod 12` draws each gradient with
/// probability ~1/12, which fixes the directional bias of the old `hash & 13`
/// set (that one over-weighted some edges, biasing the gradient field).
#[inline(always)]
fn grad3d_vec<S: Simd>(seed: i32, i: S::Vi32, j: S::Vi32, k: S::Vi32) -> [S::Vf32; 3] {
    let hash = hash3d_i32::<S>(seed, i, j, k);
    // index = (hm * 12) >> 15 for hm in 0..0x7FFF maps uniformly onto 0..=11.
    let hm = hash & S::Vi32::set1(0x7FFF);
    let index = (hm * S::Vi32::set1(12)) >> 15;

    let one = S::Vf32::set1(1.0);
    let neg = S::Vf32::set1(-1.0);
    let zero = S::Vf32::zeroes();

    // sign0 from bit 0, sign1 from bit 1: +1 when the bit is clear, -1 when set.
    let bit0_clear = (index & S::Vi32::set1(1))
        .cmp_eq(S::Vi32::zeroes())
        .bitcast_f32();
    let bit1_clear = (index & S::Vi32::set1(2))
        .cmp_eq(S::Vi32::zeroes())
        .bitcast_f32();
    let sign0 = bit0_clear.blendv(neg, one);
    let sign1 = bit1_clear.blendv(neg, one);

    let idx_lt4 = index.cmp_lt(S::Vi32::set1(4)).bitcast_f32();
    let idx_lt8 = index.cmp_lt(S::Vi32::set1(8)).bitcast_f32();

    // gx = sign0 for index < 8 (blocks 0 and 1), else 0.
    let gx = idx_lt8.blendv(zero, sign0);
    // gy = sign1 for index < 4; 0 for 4..=7; sign0 for index >= 8.
    let gy_mid = idx_lt8.blendv(sign0, zero);
    let gy = idx_lt4.blendv(gy_mid, sign1);
    // gz = 0 for index < 4, else sign1.
    let gz = idx_lt4.blendv(sign1, zero);

    debug_assert_eq!(
        gx[0].abs() + gy[0].abs() + gz[0].abs(),
        2.0,
        "exactly two axes are chosen"
    );
    [gx, gy, gz]
}

/// Generates a random gradient vector from the origin towards the midpoint of an edge of a
/// double-unit cube and computes its dot product with [x, y, z]
#[inline(always)]
pub fn grad3d_dot<S: Simd>(
    seed: i32,
    i: S::Vi32,
    j: S::Vi32,
    k: S::Vi32,
    x: S::Vf32,
    y: S::Vf32,
    z: S::Vf32,
) -> S::Vf32 {
    let [gx, gy, gz] = grad3d_vec::<S>(seed, i, j, k);
    gx * x + gy * y + gz * z
}

/// The gradient vector generated by `grad3d_dot`
///
/// This is a separate function because it's slower than `grad3d_dot` and only needed when computing
/// derivatives.
pub fn grad3d<S: Simd>(seed: i32, i: S::Vi32, j: S::Vi32, k: S::Vi32) -> [S::Vf32; 3] {
    grad3d_vec::<S>(seed, i, j, k)
}

#[inline(always)]
pub fn grad4<S: Simd>(
    seed: i32,
    hash: S::Vi32,
    x: S::Vf32,
    y: S::Vf32,
    z: S::Vf32,
    t: S::Vf32,
) -> S::Vf32 {
    let h = seed_hash::<S>(seed, hash) & S::Vi32::set1(31);
    let mut mask = (S::Vi32::set1(24).cmp_gt(h)).bitcast_f32();
    let u = mask.blendv(y, x);
    mask = (S::Vi32::set1(16).cmp_gt(h)).bitcast_f32();
    let v = mask.blendv(z, y);
    mask = (S::Vi32::set1(8).cmp_gt(h)).bitcast_f32();
    let w = mask.blendv(t, z);

    let h_and_1 = ((h & S::Vi32::set1(1)).cmp_eq(S::Vi32::zeroes())).bitcast_f32();
    let h_and_2 = ((h & S::Vi32::set1(2)).cmp_eq(S::Vi32::zeroes())).bitcast_f32();
    let h_and_4 = ((h & S::Vi32::set1(4)).cmp_eq(S::Vi32::zeroes())).bitcast_f32();

    h_and_1.blendv(S::Vf32::zeroes() - u, u)
        + h_and_2.blendv(S::Vf32::zeroes() - v, v)
        + h_and_4.blendv(S::Vf32::zeroes() - w, w)
}

/// 5D gradient dot product. The 5D gradient set is the 80 vectors with one axis
/// zero and the other four `±1`. We pick the zeroed axis uniformly in `0..=4`
/// (via the `(hm * 5) >> 14` trick) and a sign per axis from separate hash bits,
/// then return the dot with `[x, y, z, w, u]`. Magnitude is left unnormalised
/// (like `grad4`); the simplex scale constant absorbs it.
///
/// All hash bits used stay in `0..=18`. The `seed_hash` mixer (`(h >> 13) ^ h`
/// over a wrapping multiply) only agrees between the `i32` and `i64` engines for
/// those low bits — result bit `b` XORs pre-bits `b` and `b+13`, and bit 19
/// needs pre-bit 32, which the 32-bit multiply truncates but the 64-bit one
/// keeps. Reaching bit 19+ would make the f32 and f64 kernels pick different
/// gradients. So: 14 bits (`0..=13`) select the zeroed axis, and the five sign
/// bits sit at `14..=18`.
#[inline(always)]
#[allow(clippy::too_many_arguments)]
pub fn grad5<S: Simd>(
    seed: i32,
    hash: S::Vi32,
    x: S::Vf32,
    y: S::Vf32,
    z: S::Vf32,
    w: S::Vf32,
    u: S::Vf32,
) -> S::Vf32 {
    let h = seed_hash::<S>(seed, hash);
    // Which axis is zeroed, uniform in 0..=4 (bits 0..=13).
    let zero_axis = ((h & S::Vi32::set1(0x3FFF)) * S::Vi32::set1(5)) >> 14;
    let zero = S::Vf32::zeroes();

    // `+coord` when the axis sign bit is clear, `-coord` when set (bits 14..=18).
    let sign = |coord: S::Vf32, bit: i32| -> S::Vf32 {
        ((h & S::Vi32::set1(1 << bit)).cmp_eq(S::Vi32::zeroes()))
            .bitcast_f32()
            .blendv(zero - coord, coord)
    };
    // Drop the contribution of the zeroed axis.
    let keep = |signed: S::Vf32, axis: i32| -> S::Vf32 {
        zero_axis
            .cmp_eq(S::Vi32::set1(axis))
            .bitcast_f32()
            .blendv(signed, zero)
    };

    keep(sign(x, 14), 0)
        + keep(sign(y, 15), 1)
        + keep(sign(z, 16), 2)
        + keep(sign(w, 17), 3)
        + keep(sign(u, 18), 4)
}

/// 6D gradient dot product. The 6D gradient set is the 192 vectors with one axis
/// zero and the other five `±1`. We pick the zeroed axis uniformly in `0..=5`
/// (via the `(hm * 6) >> 13` trick, 13 bits) and a sign per axis from six more
/// hash bits (`13..=18`), then return the dot with `[x, y, z, w, u, t]`.
/// Magnitude is left unnormalised; the simplex scale constant absorbs it.
///
/// As in `grad5`, every hash bit used stays in `0..=18` so the f32 and f64
/// kernels select identical gradients (see `grad5` for why bit 19+ diverges).
#[inline(always)]
#[allow(clippy::too_many_arguments)]
pub fn grad6<S: Simd>(
    seed: i32,
    hash: S::Vi32,
    x: S::Vf32,
    y: S::Vf32,
    z: S::Vf32,
    w: S::Vf32,
    u: S::Vf32,
    t: S::Vf32,
) -> S::Vf32 {
    let h = seed_hash::<S>(seed, hash);
    // Which axis is zeroed, uniform in 0..=5 (bits 0..=12).
    let zero_axis = ((h & S::Vi32::set1(0x1FFF)) * S::Vi32::set1(6)) >> 13;
    let zero = S::Vf32::zeroes();

    // `+coord` when the axis sign bit is clear, `-coord` when set (bits 13..=18).
    let sign = |coord: S::Vf32, bit: i32| -> S::Vf32 {
        ((h & S::Vi32::set1(1 << bit)).cmp_eq(S::Vi32::zeroes()))
            .bitcast_f32()
            .blendv(zero - coord, coord)
    };
    // Drop the contribution of the zeroed axis.
    let keep = |signed: S::Vf32, axis: i32| -> S::Vf32 {
        zero_axis
            .cmp_eq(S::Vi32::set1(axis))
            .bitcast_f32()
            .blendv(signed, zero)
    };

    keep(sign(x, 13), 0)
        + keep(sign(y, 14), 1)
        + keep(sign(z, 15), 2)
        + keep(sign(w, 16), 3)
        + keep(sign(u, 17), 4)
        + keep(sign(t, 18), 5)
}
